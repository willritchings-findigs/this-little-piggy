"""Phase 1c (CHECKPOINT): measure Gong coverage of the 845-deal cohort and test whether coverage is biased.
Outputs: reports/01_coverage_report.md, data/outputs/deal_coverage.csv, data/outputs/coverage_by_dimension.csv, data/outputs/coverage_weights.csv
Coverage levels per deal:
  any_call        : >=1 matched call of any kind (incl. dialer / no-connect)
  any_meeting     : >=1 matched call with an external participant and duration >= MIN_MEETING_SECONDS
  discovery_plus  : >=1 meeting at stage Discovery or later
Weights: inverse-probability weights by stratum (outcome x exit tier x segment group x period) = N_stratum / n_covered_stratum,
capped at 10; strata with 0 covered deals are reported as UNREPRESENTED (cannot be extrapolated to).
"""
import pandas as pd, numpy as np
from scipy import stats
from config import COHORT, OUT, REPORTS
from stats_utils import wilson, flag

DIMS = ["outcome", "funnel_tier_exit", "highest_stage", "segment", "close_quarter", "created_pre_migration", "record_source",
        "deal_owner", "sdr_owner_correct", "deal_source", "reason_bucket"]

def main():
    c = pd.read_csv(COHORT, dtype=str)
    m = pd.read_csv(OUT / "call_deal_map.csv", dtype={"deal_id": str})
    m["is_meeting"] = m.is_meeting.astype(str).str.lower() == "true"
    g = m.groupby("deal_id")
    c["n_calls"] = c.deal_id.map(g.size()).fillna(0).astype(int)
    c["n_meetings"] = c.deal_id.map(m[m.is_meeting].groupby("deal_id").size()).fillna(0).astype(int)
    disc = m[m.is_meeting & ~m.stage_at_call.isin(["Pre-deal (before Intro)", "Intro & Challenge"])]
    c["n_meetings_discovery_plus"] = c.deal_id.map(disc.groupby("deal_id").size()).fillna(0).astype(int)
    c["any_call"] = (c.n_calls > 0).astype(int); c["any_meeting"] = (c.n_meetings > 0).astype(int); c["discovery_plus"] = (c.n_meetings_discovery_plus > 0).astype(int)
    c["match_best"] = c.deal_id.map(g.match_confidence.agg(lambda s: "high" if (s == "high").any() else "medium"))
    c.to_csv(OUT / "deal_coverage.csv", index=False)

    rows, tests = [], []
    for d in DIMS:
        for v, gg in c.groupby(d, dropna=False):
            n = len(gg); k = gg.any_meeting.sum(); lo, hi = wilson(k, n)
            rows.append({"dimension": d, "value": v, "deals": n, "with_meeting": k, "coverage": k / n if n else np.nan, "ci_low": lo, "ci_high": hi,
                         "with_any_call": gg.any_call.sum(), "with_discovery_plus_meeting": gg.discovery_plus.sum(), "covered_n_flag": flag(k)})
        ct = pd.crosstab(c[d].fillna("NA"), c.any_meeting)
        if ct.shape[1] == 2 and ct.shape[0] > 1:
            chi2, p, dof, exp = stats.chi2_contingency(ct)
            tests.append({"dimension": d, "chi2": chi2, "dof": dof, "p_value": p, "min_expected": exp.min(), "biased_at_0.05": p < 0.05})
    cov = pd.DataFrame(rows); cov.to_csv(OUT / "coverage_by_dimension.csv", index=False)
    tt = pd.DataFrame(tests)

    # IPW strata
    c["seg_grp"] = np.where(c.segment == "SMB", "SMB", "MM+Ent")
    c["period"] = np.where(pd.to_datetime(c.close_date) < "2026-04-01", "H1", "H2")
    c["stratum"] = c.outcome + "|" + c.funnel_tier_exit + "|" + c.seg_grp + "|" + c.period
    s = c.groupby("stratum").agg(N=("deal_id", "size"), n_cov=("any_meeting", "sum")).reset_index()
    s["weight"] = np.where(s.n_cov > 0, np.minimum(s.N / s.n_cov.replace(0, np.nan), 10), np.nan)
    s["status"] = np.where(s.n_cov == 0, "UNREPRESENTED", np.where(s.N / s.n_cov.replace(0, np.nan) > 10, "WEIGHT_CAPPED", "ok"))
    s.to_csv(OUT / "coverage_weights.csv", index=False)
    c.merge(s[["stratum", "weight"]], on="stratum")[["deal_id", "stratum", "weight", "any_meeting"]].to_csv(OUT / "deal_weights.csv", index=False)

    tot = len(c); km = c.any_meeting.sum()
    L = [f"# Gong coverage report — New Logo closed-deal cohort\n",
         f"Cohort: {tot} deals ({(c.outcome=='Won').sum()} won / {(c.outcome=='Lost').sum()} lost). Generated by src/03_coverage_report.py.\n",
         "## Headline\n",
         f"- Deals with any matched Gong call: {c.any_call.sum()} ({c.any_call.mean():.1%})",
         f"- Deals with ≥1 held meeting (external participant, ≥ min duration): {km} ({km/tot:.1%}, 95% CI {wilson(km,tot)[0]:.1%}–{wilson(km,tot)[1]:.1%})",
         f"- Deals with ≥1 meeting at Discovery or later: {c.discovery_plus.sum()} ({c.discovery_plus.mean():.1%})",
         f"- Won deals with a meeting: {c[c.outcome=='Won'].any_meeting.sum()} of {(c.outcome=='Won').sum()} — this is the CONTROL GROUP size for every won-vs-lost comparison",
         f"- Matched calls by method: {m.method.value_counts().to_dict()}\n",
         "## Volume and cost forecast for Phases 2–4\n",
         f"- In-scope meetings (external participant, ≥ min duration): {int(m.is_meeting.sum())} calls across {km} deals; total recorded minutes ≈ {m[m.is_meeting].duration_s.fillna(0).sum()/60:,.0f}",
         f"- Gong requests for Phase 2 (content + transcripts, 100 calls per request): ≈ {2*int(np.ceil(m.is_meeting.sum()/100))} (+pagination)",
         f"- Estimated transcript tokens ≈ {m[m.is_meeting].duration_s.fillna(0).sum()/60*150*1.35:,.0f} (≈150 spoken words/min × 1.35 tokens/word); calibration ≈ 60 calls × 2 models; production via Batch API with cached system prompt",
         f"- Calls below the meeting threshold (dialer / no-connect / very short): {int((~m.is_meeting).sum())} — counted for coverage, never transcribed or coded\n",
         "## Is coverage biased? (chi-square of coverage vs dimension)\n",
         tt.to_markdown(index=False, floatfmt=".4f") if len(tt) else "_no tests_", "\n",
         "Interpretation rule: a dimension with p < 0.05 means covered deals are NOT representative on that dimension. Analyses must then stratify by it or use the IPW weights, and report weighted and unweighted results side by side.\n",
         "## Coverage by dimension\n"]
    for d in DIMS:
        L.append(f"### {d}\n"); L.append(cov[cov.dimension == d].drop(columns="dimension").to_markdown(index=False, floatfmt=".3f")); L.append("")
    L += ["## Inverse-probability weighting strata\n", s.to_markdown(index=False, floatfmt=".2f"), "",
          "UNREPRESENTED strata cannot be described from transcripts at all — say so explicitly in findings. WEIGHT_CAPPED strata are under-covered; treat extrapolations as directional.\n",
          "## CHECKPOINT — stop here\n",
          "Claude Code: summarise this report for Will in ≤15 lines (overall coverage, biggest gaps, which paper findings can and cannot be tested at reportable n), propose any scope change, and WAIT for approval before Phase 2."]
    (REPORTS / "01_coverage_report.md").write_text("\n".join(L), encoding="utf-8")
    print(f"[ok] Coverage: {km}/{tot} deals with a held meeting ({km/tot:.1%}). Report: reports/01_coverage_report.md")
    print("[STOP] Checkpoint: review coverage with Will before pulling transcripts.")

if __name__ == "__main__":
    main()
